# ---------------------------------------------------------------- helpers


class Asm:
    def __init__(self):
        self.lines = [";; generated by tools/gen_data.py - do not edit", ""]

    def label(self, name):
        self.lines.append(f"{name}:")

    def align(self):
        self.lines.append("        IF ($ & 255) != 0")
        self.lines.append("        DS 256 - ($ & 255)")
        self.lines.append("        ENDIF")

    def db(self, data, per=16):
        data = list(data)
        for i in range(0, len(data), per):
            chunk = data[i:i + per]
            self.lines.append("        DB " + ",".join(str(int(v) & 255) for v in chunk))

    def dw(self, data, per=8):
        data = list(data)
        for i in range(0, len(data), per):
            chunk = data[i:i + per]
            self.lines.append("        DW " + ",".join(str(int(v) & 0xFFFF) for v in chunk))

    def equ(self, name, value):
        self.lines.append(f"{name} EQU {value}")

    def comment(self, text):
        self.lines.append(f";; {text}")

    def table(self, name, data, aligned=True):
        if aligned:
            self.align()
        self.label(name)
        self.db(data)

    def save(self, path):
        path.write_text("\n".join(self.lines) + "\n")


K, B, R, M, G, C, Y, W = range(8)


def ink(color, bright):
    return color | (0x40 if bright else 0)


def paper(color, bright):
    return (color << 3) | (0x40 if bright else 0)


# 16 level heat ramps (colour, bright)
RAMP_FIRE = [(K, 0), (K, 0), (R, 0), (R, 0), (R, 0), (R, 1), (R, 1), (R, 1),
             (Y, 0), (Y, 0), (Y, 1), (Y, 1), (Y, 1), (W, 0), (W, 1), (W, 1)]
RAMP_QUAD = [(K, 0), (K, 0), (B, 0), (B, 0), (B, 0), (B, 1), (B, 1), (B, 1),
             (C, 0), (C, 0), (C, 1), (C, 1), (C, 1), (W, 0), (W, 1), (W, 1)]


FIRE_STEPS = [(K, K, 0), (K, R, 0), (K, R, 1), (R, R, 1), (R, Y, 0),
              (R, Y, 1), (Y, Y, 1), (Y, W, 0), (Y, W, 1), (W, W, 1)]
QUAD_STEPS = [(K, K, 0), (K, B, 0), (K, B, 1), (B, B, 1), (B, C, 0),
              (B, C, 1), (C, C, 1), (C, W, 0), (C, W, 1), (W, W, 1)]


def step_attr(st):
    pa, ik, br = st
    return (pa << 3) | ik | (0x40 if br else 0)


def tile_ramp_mono(steps):
    return [step_attr(steps[min(len(steps) - 1, v * len(steps) // 256)]) for v in range(256)]


def tile_ramp_pp(steps):
    out = []
    for v in range(256):
        p = (v % 128) / 64.0
        p = p if p < 1 else 2 - p
        out.append(step_attr(steps[min(len(steps) - 1, int(p * len(steps)))]))
    return out


def enc_tables(ramp):
    top = [ink(*ramp[v >> 4]) for v in range(256)]
    bot = [paper(*ramp[v >> 4]) for v in range(256)]
    return top, bot



def build_images(asm):
    rgb = g.load_256x192(ROOT / "zxQ_256x192.png")
    rgb = np.clip(rgb * 1.15, 0, 255)
    pal = (K, R, Y, W)

    scr = g.convert(rgb, allowed=pal)
    (ROOT / "gfx").mkdir(exist_ok=True)
    (ROOT / "gfx" / "loading.scr").write_bytes(scr)
    g.scr_to_png(scr, ROOT / "build" / "preview_loading.png")

    # logo only: saturated pixels above the lava
    mask = g.saturation_mask(rgb, 50, 60)
    mask[152:] = False
    # dilate a bit to keep anti-aliased edges
    m2 = mask.copy()
    m2[1:] |= mask[:-1]
    m2[:-1] |= mask[1:]
    m2[:, 1:] |= mask[:, :-1]
    m2[:, :-1] |= mask[:, 1:]
    logo_rgb = rgb * m2[..., None]
    lscr = g.convert(logo_rgb, allowed=pal)
    g.scr_to_png(lscr, ROOT / "build" / "preview_logo.png")

    # crop: char columns 7..24 (18), char rows 1..18 (lines 8..151)
    asm.comment("logo bitmap: 18 bytes x 144 lines (char col 7, line 8)")
    asm.equ("LOGO_COL", 7)
    asm.equ("LOGO_W", 18)
    asm.equ("LOGO_LINE", 8)
    asm.equ("LOGO_H", 144)
    bmp = []
    for y in range(8, 152):
        for cx in range(7, 25):
            bmp.append(lscr[g.scr_offset(cx * 8, y)])
    asm.label("logo_pad")
    asm.db([0] * (8 * 18), 18)
    asm.label("logo_bmp")
    asm.db(bmp, 18)
    asm.db([0] * (8 * 18), 18)
    # melt: source line address for s = line + displacement + 8 (0..159)
    asm.align()
    asm.label("mo_lo")
    asm.lines += [f"        DB low (logo_pad + {n * 18})" for n in range(160)]
    asm.align()
    asm.label("mo_hi")
    asm.lines += [f"        DB high (logo_pad + {n * 18})" for n in range(160)]
    # displacement tables (+8) for amplitudes 8, 4, 2 pixels
    for k, shift in enumerate((4, 5, 6)):
        d = [(int(round(127 * math.sin(2 * math.pi * i / 256))) >> shift) + 8 for i in range(256)]
        asm.table(f"melt_disp{k}", d)
    attrs = []
    for cy in range(1, 19):
        for cx in range(7, 25):
            a = lscr[6144 + cy * 32 + cx]
            if a & 0x3F == 0:
                a = R  # stray pixels of the melt effect stay visible
            attrs.append(a)
    asm.label("logo_attr")
    asm.db(attrs, 18)

    # ruins patch: the picture without the logo for char rows 11..19,
    # cols 7..24 (used by scenes that show only the bottom of the picture)
    ruin_rgb = rgb * (~m2)[..., None]
    rscr = g.convert(ruin_rgb, allowed=pal)
    g.scr_to_png(rscr, ROOT / "build" / "preview_ruins.png")
    patch = []
    for y in range(88, 160):
        for cx in range(7, 25):
            patch.append(rscr[g.scr_offset(cx * 8, y)])
    asm.label("ruins_bmp")
    asm.db(patch, 18)
    pattr = []
    for cy in range(11, 20):
        for cx in range(7, 25):
            pattr.append(rscr[6144 + cy * 32 + cx])
    asm.label("ruins_attr")
    asm.db(pattr, 18)

    # zoom texture 32x32 heat from the logo, encoded with fire ramp
    crop = (logo_rgb[12:156, 56:200])  # 144x144 around the logo
    img = Image.fromarray(crop.astype(np.uint8)).resize((32, 32), Image.Resampling.BOX)
    a = np.asarray(img).astype(float)
    heat = np.clip((a[..., 0] * 0.55 + a[..., 1] * 0.45) * 1.25, 0, 255).astype(int)
    ramp = tile_ramp_mono(FIRE_STEPS)
    asm.table("zoom_tex", [ramp[heat[y, x]] for y in range(32) for x in range(32)])
    return scr


# ---------------------------------------------------------------- tables

def build_tables(asm):
    # screen line address tables
    lo = [(0x4000 + g.scr_offset(0, y)) & 255 for y in range(192)] + [0] * 64
    hi = [(0x4000 + g.scr_offset(0, y)) >> 8 for y in range(192)] + [0x40] * 64
    asm.table("line_lo", lo)
    asm.label("line_hi")
    asm.db(hi)

    # signed sine, 256 steps, amplitude 127
    sin = [round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
    asm.table("sin_tab", sin)
    # unsigned sine 0..63 for plasma
    usin = [round(31.5 + 31.5 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
    asm.label("usin_tab")
    asm.db(usin)

    # monotonic tile ramps (checkerboard bitmap): heat -> attr
    asm.table("ramp_fire", tile_ramp_mono(FIRE_STEPS))
    asm.table("ramp_quad", tile_ramp_mono(QUAD_STEPS))

    # fire decay tables
    rng = random.Random(7)
    for name, k in (("dec_tall", 11), ("dec_band", 34)):
        tab = []
        for v in range(256):
            n = v - k + rng.randint(-k // 2, k // 2)
            tab.append(max(0, min(255, n)))
        tab[0] = 0
        asm.table(name, tab)
    asm.table("rand_tab", [random.randint(0, 255) for _ in range(256)])

    # plasma tile palettes: ping-pong ramp, period 128
    asm.table("tile_fire", tile_ramp_pp(FIRE_STEPS))
    asm.table("tile_quad", tile_ramp_pp(QUAD_STEPS))

    # fade table: attr -> one step darker
    darker = {K: K, B: K, R: K, M: R, G: K, C: B, Y: R, W: Y}
    fade = []
    for a in range(256):
        ik, pa, br = a & 7, (a >> 3) & 7, a & 0x40
        if br:
            fade.append(ik | (pa << 3))
        else:
            fade.append(darker[ik] | (darker[pa] << 3))
    asm.table("fade_tab", fade)

    # lava shimmer table: attr -> hotter attr (used on lava rows)
    hot = []
    for a in range(256):
        ik, pa, br = a & 7, (a >> 3) & 7, a & 0x40
        if ik == R and not br:
            hot.append(a | 0x40)
        elif ik == R and br:
            hot.append((a & ~7 & ~0x40) | Y)
        elif ik == Y and not br:
            hot.append(a | 0x40)
        else:
            hot.append(a)
    asm.table("hot_tab", hot)
    asm.table("id_tab", list(range(256)))
    sinv = [round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
    asm.align()
    asm.label("shim_pg")
    asm.lines += ["        DB " + ("high hot_tab" if v > 50 else "high id_tab") for v in sinv]
    asm.align()
    asm.label("dot_masks")
    asm.db([0xC0, 0x30, 0x0C, 0x03])

    build_tunnel(asm)
    build_twister(asm)
    build_dots(asm)


def build_tunnel(asm):
    tab = []
    for cy in range(24):
        for cx in range(32):
            px = cx * 8 + 4 - 128
            py = cy * 8 + 4 - 96
            r = math.hypot(px, py) + 0.001
            ang = math.atan2(py, px)
            u = int(math.floor((ang / (2 * math.pi)) * 32)) & 15
            v = int(1000.0 / r) & 15
            tab.append((v << 4) | u)
    asm.table("tunnel_tab", tab)
    hole = []
    for cy in range(24):
        for cx in range(32):
            if math.hypot(cx * 8 + 4 - 128, (cy * 8 + 4 - 96)) < 30:
                hole.append(0x5800 + cy * 32 + cx)
    asm.label("tunnel_hole")
    asm.dw(hole + [0])
    fog = []
    for cy in range(24):
        for cx in range(32):
            d = math.hypot(cx * 8 + 4 - 128, (cy * 8 + 4 - 96))
            if 30 <= d < 58:
                fog.append(0x5800 + cy * 32 + cx)
    asm.label("tunnel_fog")
    asm.dw(fog + [0])

    # 16x16 texture: index = v*16+u, v = depth, u = angle
    # bright ring bands with dark mortar, radial ribs, a few lava spots
    ring = [16, 90, 150, 190, 210, 180, 120, 50]
    tex = []
    rng = random.Random(3)
    for v in range(16):
        for u in range(16):
            lv = ring[v % 8]
            if u % 8 == 0:
                lv = lv // 3
            elif u % 8 == 4 and v % 8 in (2, 3, 4, 5):
                lv = 250
            lv += rng.randint(-10, 10)
            tex.append(max(0, min(255, lv)))
    for name, steps in (("fire", FIRE_STEPS), ("quad", QUAD_STEPS)):
        ramp = tile_ramp_mono(steps)
        asm.table(f"ttex_{name}", [ramp[v] for v in tex])


def build_twister(asm):
    # 2 dither phases x 64 angles x 8 bytes; 64 angles span 90 degrees
    patterns = [
        (0xFF, 0xFF),   # face 0 solid
        (0xAA, 0x55),   # face 1 checker
        (0xEE, 0xBB),   # face 2 dense
        (0x88, 0x22),   # face 3 sparse
    ]
    out = []
    for phase in (0, 1):
        for a in range(64):
            theta = a * (math.pi / 2) / 64
            xs = [32 + 30 * math.sin(theta + k * math.pi / 2) for k in range(4)]
            row = [0] * 64
            for k in range(4):
                x0, x1 = xs[k], xs[(k + 1) % 4]
                if x1 <= x0 + 0.5:
                    continue
                pat = patterns[k][phase]
                for x in range(int(round(x0)) + 1, int(round(x1))):
                    if 0 <= x < 64 and pat & (0x80 >> (x & 7)):
                        row[x] = 1
            for xb in range(8):
                b = 0
                for i in range(8):
                    if row[xb * 8 + i]:
                        b |= 0x80 >> i
                out.append(b)
    asm.align()
    asm.label("twist_tab")
    asm.db(out)


def build_dots(asm):
    """96-point Q rune. The shape is mirror symmetric (x -> -x, z -> -z),
    so 32 frames covering 180 degrees loop seamlessly."""
    pts = []
    # crescent: open at the top, thicker at the bottom, front+back layer
    for i in range(22):
        a = math.radians(-140 + 280 * i / 21)       # 0 = bottom
        thick = 0.10 + 0.16 * math.cos(a / 2.0)
        for r in (1.0, 1.0 - thick):
            for z in ((-0.07, 0.07) if r == 1.0 else (0.0,)):
                pts.append((r * math.sin(a), r * math.cos(a), z))
    # nail shaft
    for i in range(12):
        pts.append((0.0, -0.42 + i * 0.13, 0.0))
    # cross guard
    for x in (-0.30, -0.20, -0.10, 0.10, 0.20, 0.30):
        pts.append((x, -0.22, 0.0))
    # head
    for x, y in ((-0.08, -0.48), (0.08, -0.48)):
        pts.append((x, y, 0.0))
    n = 96
    assert len(pts) <= n, len(pts)
    while len(pts) < n:
        pts.append(pts[len(pts) % 20])
    frames = 32
    data = []
    for f in range(frames):
        ay = math.pi * f / frames
        ax = math.radians(16) * math.sin(2 * math.pi * f / frames)
        for (x, y, z) in pts:
            x1 = x * math.cos(ay) + z * math.sin(ay)
            z1 = -x * math.sin(ay) + z * math.cos(ay)
            y1 = y * math.cos(ax) - z1 * math.sin(ax)
            z2 = y * math.sin(ax) + z1 * math.cos(ax)
            d = 3.0 / (3.0 + z2)
            sx = 128 + x1 * 70 * d
            sy = 80 + y1 * 70 * d
            sx = int(sx) & ~1
            sy = max(0, min(150, int(sy)))
            data += [sx, sy]
    attrs = []
    for cy in range(18):
        for cx in range(32):
            d = math.hypot(cx * 8 + 4 - 128, cy * 8 + 4 - 80) / 70
            attrs.append(0x47 if d < 0.3 else 0x46 if d < 0.65 else 0x42 if d < 0.95 else 0x02)
    asm.label("dots_attr")
    asm.db(attrs, 32)
    asm.equ("DOTS_N", n)
    asm.equ("DOTS_FRAMES", frames)
    asm.label("dots_tab")
    asm.db(data)


# ---------------------------------------------------------------- music

NOTE_NAMES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6,
              "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def note(n):
    """'E2' -> midi, '.' -> hold (0), '-' -> off (1)."""
    if n == ".":
        return 0
    if n == "-":
        return 1
    name, octave = n[:-1], int(n[-1])
    return 12 * (octave + 1) + NOTE_NAMES[name]


KICK, SNARE, HAT, CRASH = 1, 2, 4, 8


def seq(text):
    """16-step sequence 'E2 . E3 ...' -> list of 16 midi/hold codes."""
    toks = text.split()
    assert len(toks) == 16, text
    return [note(t) for t in toks]


def drums(text):
    """'k.h.s.h.' style: k kick, s snare, h hat, c crash, x kick+crash, . none."""
    toks = text.replace(" ", "")
    assert len(toks) == 16, text
    m = {"k": KICK, "s": SNARE, "h": HAT, "c": CRASH, "x": KICK | CRASH,
         "b": KICK | SNARE, ".": 0}
    return [m[c] for c in toks]


ARP_MIN, ARP_MAJ, ARP_POW = 0x10, 0x20, 0x30


def build_music(asm):
    """E minor, 125 BPM, 16 rows per bar, 2 bars per scene.
    Lead row flags (in the drum byte, bits 4-5) turn a lead note into a
    fast arpeggiated chord: minor, major or power (root, fifth, octave)."""

    def bar(text):
        return seq(text)

    # ---- bass lines (driving 8ths with octave jumps)
    B_EM = bar("E2 .  E3 .  E2 .  E3 .  E2 .  E3 .  E2 .  B2 .")
    B_C = bar("C2 .  C3 .  C2 .  C3 .  C2 .  C3 .  C2 .  G2 .")
    B_D = bar("D2 .  D3 .  D2 .  D3 .  D2 .  D3 .  D2 .  A2 .")
    B_B = bar("B1 .  B2 .  B1 .  B2 .  B1 .  B2 .  A2 .  F#2 .")
    B_AM = bar("A1 .  A2 .  A1 .  A2 .  A1 .  A2 .  A1 .  E2 .")
    B_EM_L = bar("E2 .  .  .  .  .  .  .  .  .  .  .  .  .  .  .")
    B_C_L = bar("C2 .  .  .  .  .  .  .  .  .  .  .  .  .  .  .")
    B_EM_H = bar("E2 .  .  .  .  .  .  .  E2 .  .  .  .  .  D2 .")
    B_C_H = bar("C2 .  .  .  .  .  .  .  C2 .  .  .  .  .  B1 .")
    OFF = bar("- . . . . . . . . . . . . . . .")
    REST = bar(". . . . . . . . . . . . . . . .")

    # ---- chord pads (arpeggio on the lead channel, one note per bar)
    P_EM = (bar("E4 . . . . . . . . . . . . . . ."), ARP_MIN)
    P_C = (bar("C4 . . . . . . . . . . . . . . ."), ARP_MAJ)
    P_D = (bar("D4 . . . . . . . . . . . . . . ."), ARP_MAJ)
    P_B = (bar("B3 . . . . . . . . . . . . . . ."), ARP_MAJ)
    P_EM8 = (bar("E4 . . . . . . . E4 . . . . . . ."), ARP_MIN)
    P_C8 = (bar("C4 . . . . . . . C4 . . . . . . ."), ARP_MAJ)

    # ---- the theme
    T1 = bar("E5 .  .  .  B4 .  E5 .  F#5 . G5 .  F#5 . E5 .")
    T2 = bar("G5 .  .  .  E5 .  C5 .  D5 .  E5 .  D5 .  C5 .")
    T3 = bar("D5 .  .  .  A4 .  D5 .  E5 .  F#5 . E5 .  D5 .")
    T4 = bar("D#5 . .  .  B4 .  F#4 . B4 .  .  .  .  .  -  .")
    T5 = bar("B5 .  A5 .  G5 .  F#5 . G5 .  .  .  E5 .  .  .")
    T6 = bar("C5 .  D5 .  E5 .  G5 .  E5 .  .  .  C5 .  .  .")
    T7 = bar("A4 .  C5 .  E5 .  A5 .  G5 .  E5 .  C5 .  A4 .")
    T8 = bar("B4 .  D#5 . F#5 . B5 .  A5 .  F#5 . D#5 . B4 .")
    S1 = bar("E5 .  .  .  .  .  .  .  D5 .  .  .  .  .  .  .")
    S2 = bar("C5 .  .  .  .  .  .  .  B4 .  .  .  .  .  .  .")
    E1 = bar("G5 .  .  .  F#5 . .  .  E5 .  .  .  .  .  .  .")
    E2 = bar("E4 .  .  .  .  .  .  .  .  .  .  .  .  .  .  -")

    # ---- drums
    D_NONE = drums("................")
    D_THUNDER = drums("c...............")
    D_BEAT = drums("k...k...k...k...")
    D_BASIC = drums("k...s...k...s...")
    D_GROOVE = drums("k.h.s.h.k.h.s.h.")
    D_GROOVEC = drums("x.h.s.h.k.h.s.h.")
    D_FILL = drums("k.h.s.h.k.h.ssss")
    D_ROLL = drums("k.h.s.h.bsssssss")
    D_HALF = drums("x.......s.......")
    D_HALF2 = drums("k.......s.....s.")
    D_QUAD = drums("x.hkb.hkk.hkb.hk")

    def plain(lead):
        return (lead, 0)

    # per scene: two bars of (bass, (lead, arp), drums)
    scenes = [
        # 1 sparks: drone and dark chords
        [(B_EM_L, P_EM, D_THUNDER), (B_C_L, P_C, D_THUNDER)],
        # 2 fire rising
        [(B_EM, P_EM8, D_BEAT), (B_C, P_C8, D_BEAT)],
        # 3 logo burn-in
        [(B_D, P_D, drums("x...s...k...s...")), (B_B, P_B, D_FILL)],
        # 4 logo melt: the theme
        [(B_EM, plain(T1), D_GROOVEC), (B_C, plain(T2), D_GROOVE)],
        # 5 plasma
        [(B_D, plain(T3), D_GROOVEC), (B_B, plain(T4), D_FILL)],
        # 6 tunnel
        [(B_EM, plain(T5), D_GROOVEC), (B_C, plain(T6), D_ROLL)],
        # 7 3D rune: breakdown
        [(B_EM_H, plain(S1), D_HALF), (B_C_H, plain(S2), D_HALF2)],
        # 8 zoom
        [(B_AM, plain(T7), D_GROOVEC), (B_B, plain(T8), D_FILL)],
        # 9 ruins + scroller: theme again
        [(B_EM, plain(T1), D_GROOVEC), (B_C, plain(T2), D_GROOVE)],
        # 10 twister
        [(B_D, plain(T3), D_GROOVEC), (B_B, plain(T4), D_ROLL)],
        # 11 quad damage
        [(B_EM, plain(T5), D_QUAD), (B_C, plain(T6), D_QUAD)],
        # 12 finale
        [(B_AM, plain(E1), D_THUNDER), (B_EM_L, (E2, ARP_MIN), D_NONE)],
        # 13 silence before the loop
        [(OFF, plain(OFF), D_NONE), (REST, plain(REST), D_NONE)],
    ]
    rows = []
    for sc in scenes:
        for bass, (lead, arp), dr in sc:
            for i in range(16):
                flags = arp if lead[i] > 1 else 0
                rows += [bass[i], lead[i], dr[i] | flags]
    asm.comment(f"{len(rows) // 3} rows, 3 bytes each: bass, lead, drums|arp")
    asm.label("music_rows")
    asm.db(rows, 15)
    asm.db([0xFF, 0xFF, 0])

    # frequency table: midi -> phase increment for the tone loop
    f_loop = CPU_HZ / TONE_LOOP_T
    incs = []
    for m in range(128):
        f = 440.0 * 2 ** ((m - 69) / 12)
        incs.append(min(0x7FFF, round(f * 65536 / f_loop)))
    asm.align()
    asm.label("freq_tab")
    asm.dw(incs)
    # kick drum pitch sweep (index = frames left)
    kick = [0] + [round(f * 65536 / f_loop) for f in (45, 70, 110, 170)]
    asm.label("kick_tab")
    asm.dw(kick)
    # pitch correction: index = average steps per frame - 220,
    # value m (signed) so that increment * (1 + m/256) = increment * 312/steps
    adapt = []
    for i in range(256):
        n = 220 + min(i, 119)
        m = round((312.0 / n - 1.0) * 256)
        adapt.append(max(-128, min(127, m)) & 255)
    asm.align()
    asm.label("adapt_tab")
    asm.db(adapt)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (ROOT / "build").mkdir(exist_ok=True)
    asm = Asm()

#!/usr/bin/env python3
"""
gen_fx.py - generates the inner loops of all effects with the beeper
steps scheduled in (see slotgen.py and src/sound.asm).

Output: src/gen/fx_loops.asm
Every routine documents its register inputs. All routines keep the
sound contract: no EXX, no EX AF,AF', no IY.
"""

from pathlib import Path

from slotgen import Seq, schedule, loop, pad, SLOT_W

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "gen" / "fx_loops.asm"

lines = [";; generated by tools/gen_fx.py - do not edit", ""]
stats = []


def emit(name, code, steps, t_note=""):
    lines.extend(code)
    lines.append("")
    stats.append((name, steps, t_note))


def routine(name, seq, ret=True, lead_in=0):
    """Straight-line routine with an even number of steps, then RET.
    lead_in: caller overhead between two calls (counts into slot 1)."""
    code, steps, ch = schedule(seq, lead_in=lead_in, tail=10)
    if steps % 2:
        code.extend("        " + p for p in pad(SLOT_W))
        code.append(f"        CALL s{ch}")
        steps += 1
    out = [f"{name}:"] + code
    if ret:
        out.append("        RET")
    emit(name, out, steps)


# ------------------------------------------------------------------
# PLASMA row: 32 cells, v = SX[x] + SD[x+y] + SY -> tile palette
#   DE = SX (E = 0), HL = SD + y, B = palette page, IX = attr row
#   SY is patched into pl_sy0..7 before the call
# ------------------------------------------------------------------
body = Seq()
for k in range(8):
    body.i("LD A, (DE)", 7).i("INC E", 4).i("ADD A, (HL)", 7).i("INC L", 4)
    body.label(f"pl_sy{k}")
    body.i("ADD A, 0", 7).i("LD C, A", 4).i("LD A, (BC)", 7).i(f"LD (IX+{k}), A", 19)
ctrl = ["LD A, IXL", "ADD A, 8", "LD IXL, A", "AND 31", "JP NZ, plasma_row"]
code, steps = loop("plasma_row", body, ctrl, ctrl_t=8 + 7 + 8 + 7 + 10)
emit("plasma_row", code + ["        RET"], steps, "per 8 cells")

# ------------------------------------------------------------------
# TUNNEL row (tiles): DE = tunnel_tab row, C = offset, H = texture page,
#   IX = attr row
# ------------------------------------------------------------------
s = Seq()
for k in range(32):
    s.i("LD A, (DE)", 7).i("INC DE", 6).i("ADD A, C", 4).i("LD L, A", 4)
    s.i("LD A, (HL)", 7).i(f"LD (IX+{k}), A", 19)
routine("tunnel_row", s, lead_in=103)

# ------------------------------------------------------------------
# ZOOM row (tiles): DE = colU + start (D = WORKBUF page), B = row offset
#   (v & 7) * 32, H = texture page for the row, IX = attr row
# ------------------------------------------------------------------
s = Seq()
for k in range(32):
    s.i("LD A, (DE)", 7).i("INC E", 4).i("ADD A, B", 4).i("LD L, A", 4)
    s.i("LD A, (HL)", 7).i(f"LD (IX+{k}), A", 19)
routine("zoom_row", s, lead_in=40)

# ------------------------------------------------------------------
# FIRE row (tiles): HL = F[r+1] (+/-1), BC = F[r], IX = attr row
#   decay page in fr_dk*, palette page in fr_pk* (patched by fire_patch)
# ------------------------------------------------------------------
s = Seq()
for k in range(32):
    s.i("LD A, (HL)", 7).i("INC HL", 6).i("ADD A, (HL)", 7).i("RRA", 4)
    s.i("LD E, A", 4).label(f"fr_dk{k}").i("LD D, 0", 7).i("LD A, (DE)", 7)
    s.i("LD (BC), A", 7).i("INC BC", 6)
    s.i("LD E, A", 4).label(f"fr_pk{k}").i("LD D, 0", 7).i("LD A, (DE)", 7)
    s.i(f"LD (IX+{k}), A", 19)
routine("fire_row", s, lead_in=89)
# patcher: A = decay page, C = palette page
lines.append("fire_patch:")
for k in range(32):
    lines.append(f"        LD (fr_dk{k} + 1), A")
    lines.append(f"        LD HL, fr_pk{k} + 1")
    lines.append("        LD (HL), C")
lines += ["        RET", ""]

# ------------------------------------------------------------------
# LAVA SHIMMER row: HL = ATTRSNAP row, C = phase, B = shim_pg page,
#   IX = attr row. attr = (hot or identity table)[snapshot attr]
# ------------------------------------------------------------------
s = Seq()
for k in range(32):
    s.i("LD A, (HL)", 7).i("INC L", 4).i("LD E, A", 4).i("LD A, C", 4)
    s.i("ADD A, 23", 7).i("LD C, A", 4).i("LD A, (BC)", 7).i("LD D, A", 4)
    s.i("LD A, (DE)", 7).i(f"LD (IX+{k}), A", 19)
routine("shimmer_row", s)

# ------------------------------------------------------------------
# FADE: all 768 attributes one step darker. HL = $5800, D = fade page
# ------------------------------------------------------------------
body = Seq()
for k in range(6):
    body.i("LD E, (HL)", 7).i("LD A, (DE)", 7).i("LD (HL), A", 7).i("INC HL", 6)
code, steps = loop("fade_l", body, ["DEC C", "JP NZ, fade_l"], ctrl_t=14)
emit("fade_all", ["fade_all:", "        LD HL, $5800", "        LD D, high fade_tab",
                  "        LD C, 128"] + code + ["        RET"], steps, "per 6 cells")

# ------------------------------------------------------------------
# COPY: HL -> DE, BC bytes (BC multiple of 8)
# ------------------------------------------------------------------
body = Seq()
for k in range(8):
    body.i("LDI", 16)
code, steps = loop("s_copy8", body, ["JP PE, s_copy8"], ctrl_t=10)
emit("s_copy8", code + ["        RET"], steps, "8 bytes")

# ------------------------------------------------------------------
# FILL by PUSH: SP region fill. HL = end address (exclusive),
#   DE = pattern, B = number of 32-byte chunks. Region must start at a
#   place where 2 bytes below may be overwritten (ROM / buffer start).
# ------------------------------------------------------------------
# no step after the very last PUSH: the CALL would put its return
# address below the region (into the ROM for $4000) and crash.
# The last chunk runs with interrupts off (the interrupt would push
# below the region too), and the steps here are called directly
# (sA_body) so the music tick never runs on this temporary stack.
lines += ["s_pushfill:", "        DI", "        LD (pf_sp + 1), SP", "        LD SP, HL",
          "        EI", "pf_loop:", "        LD A, B", "        DEC A", "        JR NZ, pf_go",
          "        DI", "pf_go:"]
lines += ["        PUSH DE"] * 8 + ["        " + p for p in pad(SLOT_W - 88 - 10 - 15)]
lines += ["        CALL sA_body"] + ["        PUSH DE"] * 8
lines += ["        DEC B", "        JP Z, pf_done", "        CALL sB", "        JP pf_loop",
          "pf_done:", "pf_sp:  LD SP, 0", "        EI", "        RET", ""]
st1, st2 = 2, 0
stats.append(("s_pushfill", st1 + st2, "32 bytes"))

# ------------------------------------------------------------------
# FILL attr-style: HL = start, A = value, B = chunks of 8 bytes
# ------------------------------------------------------------------
body = Seq()
for k in range(8):
    body.i("LD (HL), A", 7).i("INC HL", 6)
code, steps = loop("s_fill8", body, ["DEC B", "JP NZ, s_fill8"], ctrl_t=14)
emit("s_fill8", code + ["        RET"], steps, "8 bytes")

# ------------------------------------------------------------------
# COPY LINES 18 wide: HL = source (18 bytes per line), C = first screen
#   line, B = line count, column in cl_col (patched)
# ------------------------------------------------------------------
body = Seq()
body.i("PUSH HL", 11).i("LD L, C", 4).i("LD H, high line_lo", 7).i("LD A, (HL)", 7)
body.i("INC H", 4).i("LD D, (HL)", 7).label("cl_col").i("ADD A, 0", 7).i("LD E, A", 4)
body.i("POP HL", 10).i("PUSH BC", 11)
for k in range(18):
    body.i("LDI", 16)
body.i("POP BC", 10).i("INC C", 4)
code, steps = loop("copy_lines18", body, ["DEC B", "JP NZ, copy_lines18"], ctrl_t=14)
emit("copy_lines18", code + ["        RET"], steps, "per line")

# ------------------------------------------------------------------
# COPY ROW LINES from SCRBUF (same layout): C = first line, B = lines
# ------------------------------------------------------------------
body = Seq()
body.i("LD L, C", 4).i("LD H, high line_lo", 7).i("LD A, (HL)", 7).i("INC H", 4)
body.i("LD H, (HL)", 7).i("LD L, A", 4).i("LD D, H", 4).i("LD E, L", 4)
body.i("LD A, H", 4).i("ADD A, high (SCRBUF - $4000)", 7).i("LD H, A", 4)
body.i("PUSH BC", 11)
for k in range(32):
    body.i("LDI", 16)
body.i("POP BC", 10).i("INC C", 4)
code, steps = loop("copy_buf_lines", body, ["DEC B", "JP NZ, copy_buf_lines"], ctrl_t=14)
emit("copy_buf_lines", code + ["        RET"], steps, "per line")

# ------------------------------------------------------------------
# MELT: two interlaced logo lines per iteration
#   B = line index (0 or 1 start), mf_ph / mf_dp patched
# ------------------------------------------------------------------
def melt_line(sfx):
    q = Seq()
    q.i("LD A, B", 4).i("ADD A, A", 4).i("ADD A, A", 4).label(f"mf_ph{sfx}").i("ADD A, 0", 7)
    q.i("LD L, A", 4).label(f"mf_dp{sfx}").i("LD H, 0", 7).i("LD A, (HL)", 7)
    q.i("ADD A, B", 4).i("LD L, A", 4).i("LD H, high mo_lo", 7).i("LD E, (HL)", 7)
    q.i("INC H", 4).i("LD D, (HL)", 7)
    q.i("LD A, B", 4).i("ADD A, LOGO_LINE", 7).i("LD L, A", 4).i("LD H, high line_lo", 7)
    q.i("LD A, (HL)", 7).i("INC H", 4).i("LD H, (HL)", 7).i("ADD A, LOGO_COL", 7)
    q.i("LD L, A", 4).i("EX DE, HL", 4).i("PUSH BC", 11)
    for k in range(18):
        q.i("LDI", 16)
    q.i("POP BC", 10).i("INC B", 4).i("INC B", 4)
    return q


body = melt_line("a").extend(melt_line("b"))
code, steps = loop("melt_lines", body,
                   ["LD A, B", "CP LOGO_H", "JP C, melt_lines"], ctrl_t=4 + 7 + 10)
emit("melt_lines", code + ["        RET"], steps, "per 2 lines")

# ------------------------------------------------------------------
# TWISTER: one pair of lines per iteration, B = y (even)
#   tw_ph / tw_base patched
# ------------------------------------------------------------------
body = Seq()
body.i("LD A, B", 4).i("ADD A, A", 4).label("tw_ph").i("ADD A, 0", 7).i("LD L, A", 4)
body.i("LD H, high sin_tab", 7).i("LD A, (HL)", 7).i("SRA A", 8)
body.label("tw_base").i("ADD A, 0", 7).i("AND 63", 7)
body.i("LD L, A", 4).i("LD H, 0", 7).i("ADD HL, HL", 11).i("ADD HL, HL", 11).i("ADD HL, HL", 11)
body.i("LD DE, twist_tab", 10).i("ADD HL, DE", 11).i("PUSH HL", 11)
body.i("LD A, B", 4).i("LD L, A", 4).i("LD H, high line_lo", 7).i("LD E, (HL)", 7)
body.i("INC H", 4).i("LD D, (HL)", 7).i("LD A, E", 4).i("ADD A, 12", 7).i("LD E, A", 4)
body.i("POP HL", 10).i("PUSH BC", 11)
for k in range(8):
    body.i("LDI", 16)
body.i("LD A, H", 4).i("ADD A, 2", 7).i("LD H, A", 4).i("LD A, L", 4).i("SUB 8", 7)
body.i("LD L, A", 4).i("LD A, E", 4).i("SUB 8", 7).i("LD E, A", 4).i("INC D", 4)
for k in range(8):
    body.i("LDI", 16)
body.i("POP BC", 10).i("INC B", 4).i("INC B", 4)
code, steps = loop("twist_lines", body,
                   ["LD A, B", "CP TW_LINES", "JP C, twist_lines"], ctrl_t=21)
emit("twist_lines", code + ["        RET"], steps, "per 2 lines")

# ------------------------------------------------------------------
# DOTS: one dot per iteration. IX = erase list entry, HL = new x,y,
#   B = count
# ------------------------------------------------------------------
body = Seq()
body.i("LD A, (IX+4)", 19).i("CPL", 4).i("LD C, A", 4).i("PUSH HL", 11)
body.i("LD L, (IX+0)", 19).i("LD H, (IX+1)", 19).i("AND (HL)", 7).i("LD (HL), A", 7)
body.i("LD L, (IX+2)", 19).i("LD H, (IX+3)", 19).i("LD A, C", 4).i("AND (HL)", 7)
body.i("LD (HL), A", 7).i("POP HL", 10)
body.i("LD D, (HL)", 7).i("INC HL", 6).i("LD E, (HL)", 7).i("INC HL", 6).i("PUSH HL", 11)
body.i("LD A, D", 4).i("RRCA", 4).i("AND 3", 7).i("ADD A, low dot_masks", 7).i("LD L, A", 4)
body.i("LD H, high dot_masks", 7).i("LD C, (HL)", 7).i("LD (IX+4), C", 19)
body.i("LD A, D", 4).i("RRCA", 4).i("RRCA", 4).i("RRCA", 4).i("AND 31", 7).i("LD D, A", 4)
body.i("LD L, E", 4).i("LD H, high line_lo", 7).i("LD A, (HL)", 7).i("INC H", 4)
body.i("LD H, (HL)", 7).i("ADD A, D", 4).i("LD L, A", 4).i("LD (IX+0), L", 19)
body.i("LD (IX+1), H", 19).i("LD A, C", 4).i("OR (HL)", 7).i("LD (HL), A", 7)
body.i("LD A, E", 4).i("INC A", 4).i("LD L, A", 4).i("LD H, high line_lo", 7)
body.i("LD A, (HL)", 7).i("INC H", 4).i("LD H, (HL)", 7).i("ADD A, D", 4).i("LD L, A", 4)
body.i("LD (IX+2), L", 19).i("LD (IX+3), H", 19).i("LD A, C", 4).i("OR (HL)", 7)
body.i("LD (HL), A", 7).i("LD DE, 5", 10).i("ADD IX, DE", 15).i("POP HL", 10)
code, steps = loop("dots_loop", body, ["DEC B", "JP NZ, dots_loop"], ctrl_t=14)
emit("dots_loop", code + ["        RET"], steps, "per dot")

# ------------------------------------------------------------------
# SCROLLER: one pixel shift of 16 lines. E = first line, IX = sc_buf
# ------------------------------------------------------------------
body = Seq()
body.i("LD L, E", 4).i("LD H, high line_lo", 7).i("LD A, (HL)", 7).i("INC H", 4)
body.i("LD H, (HL)", 7).i("ADD A, 31", 7).i("LD L, A", 4).i("SLA (IX+0)", 23)
for k in range(31):
    body.i("RL (HL)", 15).i("DEC L", 4)
body.i("RL (HL)", 15).i("INC IX", 10).i("INC E", 4)
code, steps = loop("scroll_lines", body, ["DEC B", "JP NZ, scroll_lines"], ctrl_t=14)
emit("scroll_lines", code + ["        RET"], steps, "per line")

# ------------------------------------------------------------------
# SPARKS: one particle per iteration, IX = particle, B = count
# ------------------------------------------------------------------
def xor_inline(q):
    """XOR a 1x2 spark at D = x, E = y (B, C, H, L, A used)."""
    q.i("LD L, E", 4).i("LD H, high line_lo", 7).i("LD A, (HL)", 7).i("INC H", 4)
    q.i("LD H, (HL)", 7).i("LD L, A", 4).i("LD A, D", 4).i("RRCA", 4).i("RRCA", 4)
    q.i("RRCA", 4).i("AND 31", 7).i("ADD A, L", 4).i("LD L, A", 4).i("LD A, D", 4)
    q.i("AND 7", 7).i("ADD A, low pix_mask", 7).i("LD C, A", 4).i("LD B, high pix_mask", 7)
    q.i("LD A, (BC)", 7).i("LD C, A", 4).i("XOR (HL)", 7).i("LD (HL), A", 7)
    q.i("INC H", 4).i("LD A, H", 4).i("AND 7", 7).i("CALL Z, xs_fix", 10)
    q.i("LD A, C", 4).i("XOR (HL)", 7).i("LD (HL), A", 7)
    return q


body = Seq()
body.i("PUSH BC", 11).i("LD D, (IX+0)", 19).i("LD E, (IX+1)", 19)
xor_inline(body)
body.i("LD A, (IX+3)", 19).i("ADD A, 11", 7).i("LD (IX+3), A", 19).i("LD L, A", 4)
body.i("LD H, high sin_tab", 7).i("LD A, (HL)", 7)
for k in range(6):
    body.i("SRA A", 8)
body.i("ADD A, (IX+0)", 19).i("LD (IX+0), A", 19)
body.i("LD A, (IX+1)", 19).i("SUB (IX+2)", 19).i("CALL C, sp_respawn", 10)
body.i("LD HL, sp_ymin", 10).i("CP (HL)", 7).i("CALL C, sp_respawn", 10)
body.i("LD (IX+1), A", 19).i("LD D, (IX+0)", 19).i("LD E, A", 4)
xor_inline(body)
body.i("LD DE, 4", 10).i("ADD IX, DE", 15).i("POP BC", 10)
code, steps = loop("sparks_loop", body, ["DEC B", "JP NZ, sparks_loop"], ctrl_t=14)
emit("sparks_loop", code + ["        RET"], steps, "per spark")

OUT.write_text("\n".join(lines) + "\n")
for name, st, note in stats:
    print(f"  {name:16s} {st:3d} steps {note}")
